#!/usr/bin/env bash
# =============================================================================
# Killercoda foreground
# =============================================================================
echo "演習環境を準備しています(3〜5分程度かかります)..."
echo "イメージ取得・ビルド・障害状態の構築を実行中です。"
echo ""

TIMEOUT=600
waited=0
while [ ! -f /opt/.lab-ready ]; do
  sleep 3
  waited=$((waited + 3))
  echo -n "."
  if [ "${waited}" -ge "${TIMEOUT}" ]; then
    echo ""
    echo "======================================================"
    echo " [警告] 環境構築が ${TIMEOUT} 秒以内に完了しませんでした。"
    echo " 以下でログを確認してください:"
    echo "   tail -50 /var/log/lab-setup.log"
    echo " よくある原因: イメージ取得の遅延、GitHubからの資材取得失敗"
    echo "======================================================"
    exit 1
  fi
done

echo ""
echo "======================================================"
echo " 準備完了。演習を開始してください。"
echo " 作業ディレクトリ: /root/lab"
echo "======================================================"
cd /root/lab
